import re
import unittest
from pathlib import Path


ROOT = Path(__file__).parents[1]
BUNDLE = ROOT / "splunk_app/splunk_adm/appserver/static/pages/atlas.js"
CONFIG = ROOT / "vite.splunk.config.ts"


class AtlasBuildTests(unittest.TestCase):
    def test_vite_iife_shadows_requirejs_define(self):
        config = CONFIG.read_text(encoding="utf-8")
        self.assertRegex(config, r'output:\s*\{\s*intro:\s*"var define;"')

    def test_packaged_atlas_bundle_has_cloud_safe_bootstrap(self):
        if not BUNDLE.is_file():
            self.skipTest("bundle is generated by npm run package")
        bundle = BUNDLE.read_text(encoding="utf-8")
        self.assertTrue(
            re.search(r"^\(function\(\)", bundle),
            "Atlas bundle must be an IIFE",
        )
        if "splunkjs/mvc" in bundle:
            self.fail("Atlas bundle contains forbidden splunkjs/mvc reference")
        if "adm.bundle.js" in bundle:
            self.fail("Atlas bundle contains legacy adm.bundle.js reference")
        if re.search(r"(?<![.\w])define\s*\(", bundle):
            self.fail("Atlas bundle contains an unqualified AMD define call")
        self.assertFalse(
            (BUNDLE.parent.parent / "adm.bundle.js").exists(),
            "legacy adm.bundle.js must not be packaged",
        )


if __name__ == "__main__":
    unittest.main()
