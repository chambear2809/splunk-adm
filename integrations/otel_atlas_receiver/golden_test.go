func goldenGeneration(schema, id string, node bool) []record {
	row := record{"schema": schema, "schema_version": 1, "kind": "object", "generation_id": id, "cluster": "synthetic-cluster", "scope": "synthetic-scope", "producer_id": "synthetic-producer", "uid": "synthetic-uid", "name": "synthetic-name", "observation_started_at": 1700000000.125, "observation_completed_at": 1700000001.5}
	if node {
		row["addresses"] = []nodeAddress{{Address: "192.0.2.8", Type: "InternalIP"}}
	} else {
		row["namespace"] = "synthetic-ns"
		row["node_name"] = "synthetic-node"
		row["host_network"] = false
		row["pod_ips"] = []string{"198.51.100.7"}
		row["phase"] = "Running"
	}
	b, _ := encoded(row)
	row["record_fingerprint"] = digest(b)
	b, _ = encoded(row)
	manifest := record{"schema": schema, "schema_version": 1, "kind": "manifest", "generation_id": id, "cluster": "synthetic-cluster", "scope": "synthetic-scope", "producer_id": "synthetic-producer", "resource_version": "rv-opaque", "observation_started_at": 1700000000.125, "observation_completed_at": 1700000001.5, "expected_count": 1, "records_sha256": digest(b), "complete": true, "validity_basis": "point_snapshot", "namespace_scope": "all"}
	return []record{row, manifest}
}
func TestSyntheticGoldenCanonical(t *testing.T) {
	special := record{"html": "<synthetic>&", "unicode": "café", "number": 1700000000.125}
	canonical, err := encoded(special)
	if err != nil {
		t.Fatal(err)
	}
	data := record{"description": "Synthetic only; generated by Go encoding/json; not a capture.", "canonical_vector": record{"value": special, "canonical_go": string(canonical), "sha256": digest(canonical)}, "generations": []record{
		{"sourcetype": "adm:k8s_node_snapshot:v1", "source": "atlas_k8s_snapshot", "events": goldenGeneration("application_atlas.k8s_node_snapshot.v1", "00000000-0000-4000-8000-000000000001", true)},
		{"sourcetype": "adm:k8s_pod_node_snapshot:v1", "source": "atlas_k8s_snapshot", "events": goldenGeneration("application_atlas.k8s_pod_node_snapshot.v1", "00000000-0000-4000-8000-000000000002", false)},
	}}
	want, err := json.MarshalIndent(data, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	want = append(want, '\n')
	path := filepath.Join("testdata", "synthetic-golden.json")
	if os.Getenv("ATLAS_WRITE_GOLDEN") == "1" {
		if err := os.WriteFile(path, want, 0644); err != nil {
			t.Fatal(err)
		}
	}
	actual, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(actual, want) {
		t.Fatal("golden differs from producer canonical encoding")
	}
}
