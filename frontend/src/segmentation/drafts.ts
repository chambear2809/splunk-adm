/**
 * Draft exports of a validated rule set. Output is text for review only:
 * nothing here contacts a cluster, controller or firewall.
 */
export interface DraftSkip {
  rule: string;
  reason: string;
}
export interface Draft {
  text: string;
  skipped: DraftSkip[];
  /** Rules represented in the draft. */
  included: number;
}
export interface DraftContext {
  window: { start: string; end: string };
  scope: string;
}

const APP_LABEL = "app.kubernetes.io/name";
const q = (value: string) => JSON.stringify(value);

function dnsLabel(value: string, max = 63): string {
  const base = value
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, max)
    .replace(/-+$/, "");
  return base || "all";
}
/** FNV-1a; keeps truncated object names unique without exposing input text. */
function shortHash(value: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < value.length; i++) {
    h ^= value.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}
function boundedName(value: string, max: number): string {
  return value.length <= max
    ? value
    : `${value.slice(0, max - 9).replace(/[-_.:]+$/, "")}-${shortHash(value)}`;
}

function header(
  kind: string,
  context: DraftContext,
  ruleSet: RuleSet,
): string[] {
  return [
    `# DRAFT ${kind} generated by the Application Atlas segmentation workbench.`,
    "# NOT APPLIED. Atlas never pushes policy or calls cluster, controller or firewall APIs.",
    `# Rule set: ${ruleSet.rules.length} rules. Evidence scope: ${context.scope}.`,
    `# Evidence window: ${context.window.start} to ${context.window.end}. Observed traffic is not a complete inventory.`,
  ];
}

type K8sSelector = Extract<Selector, { kind: "k8s" }>;
const subjectKey = (s: K8sSelector) =>
  JSON.stringify([s.cluster, s.namespace, s.workload ?? ""]);

interface Peer {
  kind: "pods" | "cidr";
  namespace?: string;
  workload?: string;
  cidr?: string;
}
function k8sPeer(subject: K8sSelector, other: Selector): Peer | string {
  if (other.kind === "cidr") return { kind: "cidr", cidr: other.cidr };
  if (other.kind === "k8s") {
    if (other.cluster !== subject.cluster)
      return "Peers in different clusters cannot be expressed in one cluster's policy.";
    return {
      kind: "pods",
      namespace: other.namespace,
      ...(other.workload ? { workload: other.workload } : {}),
    };
  }
  return `${describeSelector(other)} cannot be expressed as a Kubernetes peer.`;
}

interface Entry {
  rule: Rule;
  peer: Peer;
}
interface Subject {
  selector: K8sSelector;
  ingress: Entry[];
  egress: Entry[];
  ingressDeny: Entry[];
  egressDeny: Entry[];
}

function collectSubjects(
  ruleSet: RuleSet,
  options: { deny: boolean; protocols: readonly Protocol[]; label: string },
): { subjects: Subject[]; skipped: DraftSkip[]; included: number } {
  const subjects = new Map<string, Subject>();
  const skipped: DraftSkip[] = [];
  let included = 0;
  const subject = (selector: K8sSelector) => {
    const key = subjectKey(selector);
    let s = subjects.get(key);
    if (!s) {
      s = {
        selector,
        ingress: [],
        egress: [],
        ingressDeny: [],
        egressDeny: [],
      };
      subjects.set(key, s);
    }
    return s;
  };
  for (const rule of ruleSet.rules) {
    if (rule.action === "deny" && !options.deny) {
      skipped.push({
        rule: rule.id,
        reason: `${options.label} has no deny rules.`,
      });
      continue;
    }
    if (!options.protocols.includes(rule.protocol)) {
      skipped.push({
        rule: rule.id,
        reason: `${rule.protocol.toUpperCase()} is not emitted in the ${options.label} draft; review it manually.`,
      });
      continue;
    }
    const reasons: string[] = [];
    let used = false;
    for (const [side, own, other] of [
      ["ingress", rule.destination, rule.source],
      ["egress", rule.source, rule.destination],
    ] as const) {
      if (own.kind !== "k8s") continue;
      const peer = k8sPeer(own, other);
      if (typeof peer === "string") {
        reasons.push(peer);
        continue;
      }
      const s = subject(own);
      const list =
        rule.action === "deny"
          ? side === "ingress"
            ? s.ingressDeny
            : s.egressDeny
          : side === "ingress"
            ? s.ingress
            : s.egress;
      list.push({ rule, peer });
      used = true;
    }
    if (used) included++;
    else
      skipped.push({
        rule: rule.id,
        reason:
          reasons[0] ??
          "Neither side is a Kubernetes namespace/workload selector.",
      });
  }
  return { subjects: [...subjects.values()], skipped, included };
}

function skippedComments(skipped: DraftSkip[]): string[] {
  return skipped.length
    ? [
        "# Rules not represented in this draft:",
        ...skipped.map(
          (s) => `#   ${s.rule}: ${s.reason.replace(/\s+/g, " ")}`,
        ),
      ]
    : [];
}

export function networkPolicyDraft(
  ruleSet: RuleSet,
  context: DraftContext,
): Draft {
  const { subjects, skipped, included } = collectSubjects(ruleSet, {
    deny: false,
    protocols: ["tcp", "udp", "sctp"],
    label: "Kubernetes NetworkPolicy",
  });
  const lines = [
    ...header(
      "Kubernetes NetworkPolicy (networking.k8s.io/v1)",
      context,
      ruleSet,
    ),
    "# WARNING: a policy that selects a pod makes it default-deny for that direction.",
    "# Add DNS egress (UDP/TCP 53 to kube-dns) and verify pod labels before applying.",
    `# Atlas records the workload controller name, not pod labels: every ${APP_LABEL} value must be verified.`,
    "# endPort needs Kubernetes 1.25+ and a CNI that supports it.",
    ...skippedComments(skipped),
  ];
  const peerLines = (peer: Peer, indent: string, key: "from" | "to") => {
    if (peer.kind === "cidr")
      return [
        `${indent}- ${key}:`,
        `${indent}  - ipBlock:`,
        `${indent}      cidr: ${q(peer.cidr!)}`,
      ];
    const out = [
      `${indent}- ${key}:`,
      `${indent}  - namespaceSelector:`,
      `${indent}      matchLabels:`,
      `${indent}        kubernetes.io/metadata.name: ${q(peer.namespace!)}`,
    ];
    if (peer.workload)
      out.push(
        `${indent}    podSelector:`,
        `${indent}      matchLabels:`,
        `${indent}        ${APP_LABEL}: ${q(peer.workload)} # VERIFY label`,
      );
    return out;
  };
  const portLines = (rule: Rule, indent: string) => [
    `${indent}  ports:`,
    `${indent}  - protocol: ${rule.protocol.toUpperCase()}`,
    `${indent}    port: ${rule.ports.from}`,
    ...(rule.ports.to !== rule.ports.from
      ? [`${indent}    endPort: ${rule.ports.to}`]
      : []),
  ];
  for (const s of subjects) {
    const { selector } = s;
    const types = [
      s.ingress.length && "Ingress",
      s.egress.length && "Egress",
    ].filter(Boolean);
    lines.push(
      "---",
      `# Cluster: ${selector.cluster}`,
      "apiVersion: networking.k8s.io/v1",
      "kind: NetworkPolicy",
      "metadata:",
      `  name: ${q(boundedName(`atlas-draft-${dnsLabel(selector.workload ?? "all", 40)}`, 63))}`,
      `  namespace: ${q(selector.namespace)}`,
      "  annotations:",
      `    atlas.splunk.com/draft: "true"`,
      "spec:",
      ...(selector.workload
        ? [
            "  podSelector:",
            "    matchLabels:",
            `      ${APP_LABEL}: ${q(selector.workload)} # VERIFY label`,
          ]
        : ["  podSelector: {} # every pod in the namespace"]),
      "  policyTypes:",
      ...types.map((t) => `  - ${t}`),
    );
    if (s.ingress.length) {
      lines.push("  ingress:");
      for (const e of s.ingress)
        lines.push(
          `  # rule ${e.rule.id}`,
          ...peerLines(e.peer, "  ", "from"),
          ...portLines(e.rule, "  "),
        );
    }
    if (s.egress.length) {
      lines.push("  egress:");
      for (const e of s.egress)
        lines.push(
          `  # rule ${e.rule.id}`,
          ...peerLines(e.peer, "  ", "to"),
          ...portLines(e.rule, "  "),
        );
    }
  }
  if (!subjects.length)
    lines.push("# No rule could be represented as a Kubernetes NetworkPolicy.");
  return { text: lines.join("\n") + "\n", skipped, included };
}

export function ciliumPolicyDraft(
  ruleSet: RuleSet,
  context: DraftContext,
): Draft {
  const { subjects, skipped, included } = collectSubjects(ruleSet, {
    deny: true,
    protocols: ["tcp", "udp"],
    label: "CiliumNetworkPolicy",
  });
  const lines = [
    ...header("CiliumNetworkPolicy (cilium.io/v2)", context, ruleSet),
    "# WARNING: a policy that selects an endpoint makes it default-deny for that direction.",
    "# ingressDeny/egressDeny take precedence over allow rules. fromCIDR/toCIDR do not apply to",
    "# traffic between Cilium-managed endpoints or nodes in the cluster.",
    "# Add DNS egress, verify labels, and use per-endpoint PolicyAuditMode; never daemon-wide audit mode.",
    `# Atlas records the workload controller name, not pod labels: every ${APP_LABEL} value must be verified.`,
    ...skippedComments(skipped),
  ];
  const peerLines = (peer: Peer, indent: string, key: "from" | "to") => {
    if (peer.kind === "cidr")
      return [`${indent}- ${key}CIDR:`, `${indent}  - ${q(peer.cidr!)}`];
    return [
      `${indent}- ${key}Endpoints:`,
      `${indent}  - matchLabels:`,
      `${indent}      "k8s:io.kubernetes.pod.namespace": ${q(peer.namespace!)}`,
      ...(peer.workload
        ? [
            `${indent}      "k8s:${APP_LABEL}": ${q(peer.workload)} # VERIFY label`,
          ]
        : []),
    ];
  };
  const portLines = (rule: Rule, indent: string) => [
    `${indent}  toPorts:`,
    `${indent}  - ports:`,
    `${indent}    - port: ${q(String(rule.ports.from))}`,
    ...(rule.ports.to !== rule.ports.from
      ? [`${indent}      endPort: ${rule.ports.to}`]
      : []),
    `${indent}      protocol: ${rule.protocol.toUpperCase()}`,
  ];
  const section = (name: string, entries: Entry[], key: "from" | "to") =>
    entries.length
      ? [
          `  ${name}:`,
          ...entries.flatMap((e) => [
            `  # rule ${e.rule.id}`,
            ...peerLines(e.peer, "  ", key),
            ...portLines(e.rule, "  "),
          ]),
        ]
      : [];
  for (const s of subjects) {
    const { selector } = s;
    lines.push(
      "---",
      `# Cluster: ${selector.cluster}`,
      "apiVersion: cilium.io/v2",
      "kind: CiliumNetworkPolicy",
      "metadata:",
      `  name: ${q(boundedName(`atlas-draft-${dnsLabel(selector.workload ?? "all", 40)}`, 63))}`,
      `  namespace: ${q(selector.namespace)}`,
      "  annotations:",
      `    atlas.splunk.com/draft: "true"`,
      "spec:",
      "  endpointSelector:",
      "    matchLabels:",
      `      "k8s:io.kubernetes.pod.namespace": ${q(selector.namespace)}`,
      ...(selector.workload
        ? [`      "k8s:${APP_LABEL}": ${q(selector.workload)} # VERIFY label`]
        : []),
      ...section("ingress", s.ingress, "from"),
      ...section("ingressDeny", s.ingressDeny, "from"),
      ...section("egress", s.egress, "to"),
      ...section("egressDeny", s.egressDeny, "to"),
    );
  }
  if (!subjects.length)
    lines.push("# No rule could be represented as a CiliumNetworkPolicy.");
  return { text: lines.join("\n") + "\n", skipped, included };
}

type EpgSelector = Extract<Selector, { kind: "epg" }>;
type Mo = Record<
  string,
  { attributes: Record<string, string>; children?: Mo[] }
>;

/**
 * APIC object-model draft (fvTenant, vzFilter/vzEntry, vzBrCP/vzSubj/
 * vzRsSubjFiltAtt, fvAp/fvAEPg with fvRsCons/fvRsProv). Wrapped with draft
 * metadata so it cannot be posted to APIC unchanged.
 */
export function aciContractDraft(
  ruleSet: RuleSet,
  context: DraftContext,
): Draft {
  const skipped: DraftSkip[] = [];
  interface Pair {
    consumer: EpgSelector;
    provider: EpgSelector;
    filters: Map<string, { action: "permit" | "deny"; rule: Rule }>;
  }
  const tenants = new Map<
    string,
    { filters: Map<string, Rule>; pairs: Map<string, Pair> }
  >();
  let included = 0;
  for (const rule of ruleSet.rules) {
    const { source, destination } = rule;
    if (source.kind !== "epg" || destination.kind !== "epg") {
      skipped.push({
        rule: rule.id,
        reason:
          source.kind === "esg" || destination.kind === "esg"
            ? "ESG selectors are not evaluated by Atlas; draft ESG contracts manually."
            : "Both sides must be ACI EPG selectors.",
      });
      continue;
    }
    if (source.tenant !== destination.tenant) {
      skipped.push({
        rule: rule.id,
        reason:
          "Cross-tenant contracts (exported or tenant common) are not drafted.",
      });
      continue;
    }
    const tenant = tenants.get(source.tenant) ?? {
      filters: new Map(),
      pairs: new Map(),
    };
    tenants.set(source.tenant, tenant);
    const filterName = `atlas-${rule.protocol}-${portText(rule.ports)}`;
    tenant.filters.set(filterName, rule);
    const pairKey = JSON.stringify([
      source.appProfile,
      source.epg,
      destination.appProfile,
      destination.epg,
    ]);
    const pair = tenant.pairs.get(pairKey) ?? {
      consumer: source,
      provider: destination,
      filters: new Map(),
    };
    tenant.pairs.set(pairKey, pair);
    const action = rule.action === "allow" ? "permit" : "deny";
    const existing = pair.filters.get(filterName);
    if (existing && existing.action !== action) {
      skipped.push({
        rule: rule.id,
        reason: `Conflicts with rule ${existing.rule.id} (permit and deny for the same ports and EPG pair).`,
      });
      continue;
    }
    if (!existing) pair.filters.set(filterName, { action, rule });
    included++;
  }
  const payload: Mo[] = [];
  for (const [tenantName, tenant] of [...tenants.entries()].sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const children: Mo[] = [];
    for (const [name, rule] of [...tenant.filters.entries()].sort(([a], [b]) =>
      a.localeCompare(b),
    ))
      children.push({
        vzFilter: {
          attributes: { name },
          children: [
            {
              vzEntry: {
                attributes: {
                  name: `e-${rule.protocol}-${portText(rule.ports)}`,
                  etherT: "ip",
                  prot: rule.protocol,
                  dFromPort: String(rule.ports.from),
                  dToPort: String(rule.ports.to),
                },
              },
            },
          ],
        },
      });
    const epgs = new Map<
      string,
      Map<string, { cons: Set<string>; prov: Set<string> }>
    >();
    const relation = (s: EpgSelector) => {
      const ap = epgs.get(s.appProfile) ?? new Map();
      epgs.set(s.appProfile, ap);
      const epg = ap.get(s.epg) ?? {
        cons: new Set<string>(),
        prov: new Set<string>(),
      };
      ap.set(s.epg, epg);
      return epg;
    };
    for (const pair of tenant.pairs.values()) {
      if (!pair.filters.size) continue;
      const contract = boundedName(
        `atlas-${pair.consumer.epg}-to-${pair.provider.epg}`,
        64,
      );
      children.push({
        vzBrCP: {
          attributes: { name: contract, scope: "context" },
          children: [
            {
              vzSubj: {
                attributes: { name: "atlas-draft", revFltPorts: "yes" },
                children: [...pair.filters.entries()].map(([filter, f]) => ({
                  vzRsSubjFiltAtt: {
                    attributes: { tnVzFilterName: filter, action: f.action },
                  },
                })),
              },
            },
          ],
        },
      });
      relation(pair.consumer).cons.add(contract);
      relation(pair.provider).prov.add(contract);
    }
    for (const [ap, groups] of epgs)
      children.push({
        fvAp: {
          attributes: { name: ap },
          children: [...groups.entries()].map(([epg, r]) => ({
            fvAEPg: {
              attributes: { name: epg },
              children: [
                ...[...r.cons].map((c) => ({
                  fvRsCons: { attributes: { tnVzBrCPName: c } },
                })),
                ...[...r.prov].map((c) => ({
                  fvRsProv: { attributes: { tnVzBrCPName: c } },
                })),
              ],
            },
          })),
        },
      });
    payload.push({ fvTenant: { attributes: { name: tenantName }, children } });
  }
  const document = {
    atlasDraft: {
      status: "DRAFT - not applied",
      generatedBy: "Application Atlas segmentation workbench",
      notice: [
        "Atlas never calls the APIC API. Review every object before any manual use.",
        "Posting fvAp/fvAEPg objects creates them when they do not exist; remove EPGs you do not intend to change.",
        "Contracts use scope context (VRF). Deny actions need APIC support for deny filters; check rule priority.",
        "Observed traffic is not a complete inventory of required flows.",
      ],
      evidenceScope: context.scope,
      evidenceWindow: context.window,
      objectModel:
        "Cisco APIC MIM classes fvTenant, vzFilter, vzEntry, vzBrCP, vzSubj, vzRsSubjFiltAtt, fvAp, fvAEPg, fvRsCons, fvRsProv",
      skipped,
    },
    apicPayload: payload,
  };
  return { text: JSON.stringify(document, null, 2) + "\n", skipped, included };
}

export const FIREWALL_COLUMNS = [
  "status",
  "rule_id",
  "action",
  "protocol",
  "port_from",
  "port_to",
  "source_selector",
  "source_addresses",
  "destination_selector",
  "destination_addresses",
  "address_basis",
  "notes",
] as const;
const MAX_CELL_ADDRESSES = 32;

/**
 * Generic firewall rule rows. CIDR selectors are used as written; other
 * selectors list only addresses of endpoints that definitely matched in the
 * evidence window, which is not complete membership.
 */
export function firewallCsvDraft(
  ruleSet: RuleSet,
  graph: Pick<Graph, "nodes" | "edges">,
): Draft {
  const context = evaluationContext(graph);
  const endpointIds = new Set<string>();
  for (const edge of conversations(graph)) {
    endpointIds.add(edge.source);
    endpointIds.add(edge.target);
  }
  const resolved = (
    selector: Selector,
  ): { cell: string; observed: boolean; note?: string } => {
    if (selector.kind === "cidr")
      return { cell: selector.cidr, observed: false };
    if (selector.kind === "esg")
      return {
        cell: "",
        observed: true,
        note: "ESG membership is not evaluated by Atlas.",
      };
    const addresses = new Set<string>();
    for (const id of endpointIds) {
      const node = context.nodes.get(id);
      if (matchSelector(selector, node, context).state !== "match") continue;
      for (const address of node?.addresses ?? []) addresses.add(address);
    }
    const list = [...addresses].sort();
    if (!list.length)
      return {
        cell: "",
        observed: true,
        note: `${describeSelector(selector)} resolved to no observed address; fill manually.`,
      };
    const shown = list.slice(0, MAX_CELL_ADDRESSES).join(" ");
    return {
      cell:
        list.length > MAX_CELL_ADDRESSES
          ? `${shown} (+${list.length - MAX_CELL_ADDRESSES} more)`
          : shown,
      observed: true,
    };
  };
  const rows = [csvRow([...FIREWALL_COLUMNS])];
  for (const rule of ruleSet.rules) {
    const source = resolved(rule.source);
    const destination = resolved(rule.destination);
    const notes = [source.note, destination.note].filter(Boolean);
    rows.push(
      csvRow([
        "DRAFT",
        rule.id,
        rule.action,
        rule.protocol,
        rule.ports.from,
        rule.ports.to,
        describeSelector(rule.source),
        source.cell,
        describeSelector(rule.destination),
        destination.cell,
        source.observed || destination.observed
          ? "Addresses of endpoints matched in the evidence window; membership can change."
          : "CIDR selectors as written.",
        notes.join(" "),
      ]),
    );
  }
  return {
    text: rows.join("\r\n") + "\r\n",
    skipped: [],
    included: ruleSet.rules.length,
  };
}
